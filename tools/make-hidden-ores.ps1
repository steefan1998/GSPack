# Hide only ore blocks already covered by GSPack's disabled-generation/conversion map.
$ErrorActionPreference='Stop'
$root=Split-Path $PSScriptRoot -Parent
$source=[IO.File]::ReadAllText((Join-Path $root 'kubejs/server_scripts/gspack_zz_unify_blocks.js'))
$map=[regex]::Match($source,'(?s)const GSPACK_BLOCK_TO = \{(.*?)\n\}').Groups[1].Value
$ores=@([regex]::Matches($map,"'([^']+)': '[^']+'") | ForEach-Object { $_.Groups[1].Value } | Sort-Object -Unique)
if(-not $ores.Count){throw 'No disabled-generation ore mappings found.'}
# Refuse to silently hide a namespace without pack-owned generation overrides.
foreach($ore in $ores) {
    $namespace=($ore -split ':')[0]
    $overrides=Join-Path $root "kubejs/data/$namespace/neoforge/biome_modifier"
    if(-not(Test-Path -LiteralPath $overrides)){throw "No worldgen override evidence for $ore"}
}
$js=@(
    '// GENERATED by tools/make-hidden-ores.ps1 from the pack worldgen/conversion map.',
    '// These duplicate ores do not generate in new GSPack chunks. Existing blocks remain valid.',
    '// AllTheOres, titanium, cinnabar, raw materials and unique mod ores stay visible.',
    "RecipeViewerEvents.removeEntries('item', event => {",
    '  ['
)+@($ores | ForEach-Object {"    '$_',"})+@('  ].forEach(id => event.remove(id))','})','')
[IO.File]::WriteAllText((Join-Path $root 'kubejs/client_scripts/gspack_disabled_ores_hide.js'),($js -join "`n"),[Text.UTF8Encoding]::new($false))
"Generated JEI hiding for $($ores.Count) disabled duplicate ore blocks."
