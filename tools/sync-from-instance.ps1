# Copies the pack configuration from the GSPack instance into this repository and refreshes MODS.md.
# Usage:  powershell -ExecutionPolicy Bypass -File tools\sync-from-instance.ps1 [-Instance <path>]
param([string]$Instance = 'D:\MinecraftModpacks\Instances\GSPack')

$ErrorActionPreference = 'Stop'
$Root = Split-Path $PSScriptRoot -Parent
if (-not (Test-Path "$Instance\mods")) { throw "No mods folder in $Instance" }

# Files that hold secrets or per-user state and must never be published.
$exclude = @('resourceful-config-web.json')

foreach ($dir in 'config', 'kubejs', 'defaultconfigs') {
    if (-not (Test-Path "$Instance\$dir")) { continue }
    robocopy "$Instance\$dir" "$Root\$dir" /E /XF $exclude /NFL /NDL /NJH /NJS /NP | Out-Null
    if ($LASTEXITCODE -ge 8) { throw "robocopy failed for $dir (exit $LASTEXITCODE)" }
}

# Mod list from each jar's neoforge.mods.toml (display name + version), falling back to the file name.
Add-Type -AssemblyName System.IO.Compression.FileSystem
$rows = foreach ($jar in Get-ChildItem "$Instance\mods" -Filter *.jar | Sort-Object Name) {
    $name = $null; $ver = $null
    $zip = [System.IO.Compression.ZipFile]::OpenRead($jar.FullName)
    try {
        $e = $zip.GetEntry('META-INF/neoforge.mods.toml')
        if ($e) {
            $sr = New-Object System.IO.StreamReader($e.Open()); $toml = $sr.ReadToEnd(); $sr.Close()
            if ($toml -match '(?m)^\s*displayName\s*=\s*"([^"]+)"') { $name = $Matches[1] }
            if ($toml -match '(?m)^\s*version\s*=\s*"([^"$]+)"') { $ver = $Matches[1] }
        }
    } finally { $zip.Dispose() }
    if (-not $name) { $name = $jar.BaseName }
    if (-not $ver) { $ver = '' }
    "| $name | $ver | ``$($jar.Name)`` |"
}
$md = @("# GSPack mod list", "", "$(@($rows).Count) mods, generated by ``tools/sync-from-instance.ps1``.", "",
    "| Mod | Version | File |", "|---|---|---|") + $rows
[IO.File]::WriteAllText("$Root\MODS.md", ($md -join "`n") + "`n", (New-Object System.Text.UTF8Encoding($false)))
"Synced config/kubejs from $Instance; MODS.md lists $(@($rows).Count) mods."
