ServerEvents.generateData('after_mods', event => {
  const values = {}
  const crystals = ['diamond', 'emerald', 'fluorite', 'lapis', 'quartz', 'sapphire', 'ruby', 'peridot', 'cinnabar']
  GSPACK_THAUM_MATERIAL_TAGS.forEach(tag => {
    const parts = tag.split('/')
    const kind = parts[0]
    const material = parts[1]
    const crystal = crystals.indexOf(material) >= 0 || kind === 'gems'
    const amount = kind === 'storage_blocks' ? 27 : kind === 'nuggets' || kind === 'dusts' ? 1 : 3
    const primary = material === 'salt' ? 'terra' : material === 'sulfur' ? 'ignis' : crystal ? 'vitreus' : 'metallum'
    const aspects = [{ aspect: 'thaumaturge:' + primary, amount: amount }]
    if (kind === 'ores') aspects.push({ aspect: 'thaumaturge:terra', amount: 3 })
    if (kind === 'raw_materials') aspects.push({ aspect: 'thaumaturge:terra', amount: 1 })
    values['#c:' + tag] = aspects
  })
  event.json('thaumaturge:data_maps/item/base_aspects.json', { values: values })
})
